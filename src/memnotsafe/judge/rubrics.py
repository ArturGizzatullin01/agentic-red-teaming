def find_rubric(stage: str, effect_type: str | None) -> Rubric | None:
    """Поиск по паре (стадия, `expected_effect.type`). Для `retrieval` тип
    эффекта не важен — вопрос к стадии один. Отсутствие рубрики означает, что
    судью на этой паре звать не с чем: вызывающий обязан не делать вызова."""
    if stage == "retrieval":
        return _RETRIEVAL
    if not effect_type:
        return None
    return _RUBRICS.get(f"{stage}/{effect_type}")


def all_rubrics() -> dict[str, Rubric]:
    return dict(_RUBRICS)
