"""src/memnotsafe/generation/errors.py — тип сбоя атакующей LLM.

`AttackerError` симметричен `core/runner.py::RunnerError`, но описывает сбой
ДРУГОГО слоя — генерации/переписывания атаки: нет ключа, недоступна модель,
таймаут, отказ или неразбираемый ответ, плохая конфигурация профиля/классов.

Разделение типов — жёсткое требование (Принцип VII, FR-011): сбой атакующей
LLM (`exit 1`) НИКОГДА не выдаётся за «атака честно не пробила защиту»
(`exit 0` + `NOT_EXPLOITABLE`). Исчерпание бюджета вызовов — НЕ `AttackerError`,
а штатный стоп (см. budget.py): его инструмент переживает с `exit 0`.
"""

from __future__ import annotations


class AttackerError(RuntimeError):
    """Сбой атакующей LLM или её конфигурации. Ловится CLI/эскалацией и
    транслируется в `exit 1`, отдельно от `RunnerError` и от честного
    отрицательного результата атаки."""
