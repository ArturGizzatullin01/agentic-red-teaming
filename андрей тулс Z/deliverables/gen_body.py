def rule():
    return HRFlowable(width='100%', thickness=1.1, color=ACCENT,
                      spaceBefore=0, spaceAfter=10)


def h1_block(num, text, threshold=100):
    return [CondPageBreak(threshold),
            KeepTogether([Paragraph(f'<b>{num}. {text}</b>', h1), rule()])]


def mk_table(rows, ratios, header=True, stripe=True):
    widths = [r * avail for r in ratios]
    data = []
    for i, row in enumerate(rows):
        cells = []
        for c in row:
            st = th if (header and i == 0) else td
            cells.append(Paragraph(c, st))
        data.append(cells)
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1 if header else 0)
    style = [('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
             ('LEFTPADDING', (0, 0), (-1, -1), 6),
             ('RIGHTPADDING', (0, 0), (-1, -1), 6),
             ('TOPPADDING', (0, 0), (-1, -1), 5),
             ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
             ('GRID', (0, 0), (-1, -1), 0.4, BORDER)]
    if header:
        style += [('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR)]
    if stripe:
        for i in range(1, len(rows)):
            if i % 2 == 0:
                style.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_ODD))
    t.setStyle(TableStyle(style))
    return t


def callout_row(items):
    n = len(items)
    w = (avail - (n - 1) * 10) / n
    cells, widths = [], []
    for big, lab in items:
        inner = Table([[Paragraph(f'<b>{big}</b>', stat_big)],
                       [Paragraph(lab, stat_lab)]], colWidths=[w])
        inner.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
            ('BOX', (0, 0), (-1, -1), 0.8, BORDER),
            ('TOPPADDING', (0, 0), (-1, 0), 8),
            ('BOTTOMPADDING', (0, 1), (-1, 1), 8),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE')]))
        cells.append(inner)
        widths.append(w + 10)
    outer = Table([cells], colWidths=widths, hAlign='CENTER')
    outer.setStyle(TableStyle([('VALIGN', (0, 0), (-1, -1), 'TOP'),
                               ('LEFTPADDING', (0, 0), (-1, -1), 0),
                               ('RIGHTPADDING', (0, 0), (-1, -1), 10),
                               ('RIGHTPADDING', (-1, 0), (-1, -1), 0),
                               ('TOPPADDING', (0, 0), (-1, -1), 0),
                               ('BOTTOMPADDING', (0, 0), (-1, -1), 0)]))
    return outer


